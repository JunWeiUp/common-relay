// Command protocol-vectors regenerates the shared cross-SDK test vectors in
// protocol/v2/ from the Go implementation, deterministically:
//
//	go run ./scripts/protocol-vectors          # rewrite protocol/v2/*.json
//	go run ./scripts/protocol-vectors -check   # fail if a file is stale
//
// All keys are public test material derived from fixed seeds; never deploy them.
// group-vectors.json keeps its signed base fixtures (Ed25519 is deterministic,
// so they are stable); this tool owns its config, strict_payload and
// entry_hashes sections and verifies every base signature it relies on.
package main

import (
	"bytes"
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/base64"
	"encoding/binary"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/JunWeiUp/common-relay/internal/v2/core"
	"github.com/JunWeiUp/common-relay/sdk/go/v2client"
	"golang.org/x/crypto/curve25519"
	"golang.org/x/crypto/nacl/box"
	"golang.org/x/crypto/nacl/secretbox"
)

const generatedNote = "Generated by `go run ./scripts/protocol-vectors`; public test material only, never deploy."

func main() {
	check := flag.Bool("check", false, "verify the files are up to date instead of writing them")
	dir := flag.String("dir", "protocol/v2", "vector directory")
	flag.Parse()
	files, err := Generate(*dir)
	if err != nil {
		fail(err)
	}
	stale := false
	for _, name := range sortedKeys(files) {
		path := filepath.Join(*dir, name)
		if *check {
			old, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(old, files[name]) {
				fmt.Fprintf(os.Stderr, "stale: %s\n", path)
				stale = true
			}
			continue
		}
		if err := os.WriteFile(path, files[name], 0o644); err != nil {
			fail(err)
		}
		fmt.Println("wrote", path)
	}
	if stale {
		fail(errors.New("protocol vectors are stale; run go run ./scripts/protocol-vectors"))
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "protocol-vectors:", err)
	os.Exit(1)
}

func sortedKeys(m map[string][]byte) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	for i := 1; i < len(out); i++ {
		for j := i; j > 0 && out[j] < out[j-1]; j-- {
			out[j], out[j-1] = out[j-1], out[j]
		}
	}
	return out
}

// Generate returns the regenerated vector files keyed by file name. It reads
// the signed base fixtures from the existing group-vectors.json in dir.
func Generate(dir string) (map[string][]byte, error) {
	out := map[string][]byte{}
	var err error
	if out["vectors.json"], err = coreVectors(); err != nil {
		return nil, fmt.Errorf("vectors.json: %w", err)
	}
	if out["sealed-vectors.json"], err = sealedVectors(); err != nil {
		return nil, fmt.Errorf("sealed-vectors.json: %w", err)
	}
	groupRaw, err := os.ReadFile(filepath.Join(dir, "group-vectors.json"))
	if err != nil {
		return nil, err
	}
	if out["group-vectors.json"], err = groupVectors(groupRaw); err != nil {
		return nil, fmt.Errorf("group-vectors.json: %w", err)
	}
	linkRaw, err := os.ReadFile(filepath.Join(dir, "invitation-link-vectors.json"))
	if err != nil {
		return nil, err
	}
	if out["invitation-link-vectors.json"], err = invitationVectors(groupRaw, linkRaw); err != nil {
		return nil, fmt.Errorf("invitation-link-vectors.json: %w", err)
	}
	return out, nil
}

/* ───────── ordered JSON helpers ───────── */

type kv struct {
	K string
	V any
}

// obj marshals as a JSON object with keys in insertion order.
type obj []kv

func (o obj) MarshalJSON() ([]byte, error) {
	var b bytes.Buffer
	b.WriteByte('{')
	for i, e := range o {
		if i > 0 {
			b.WriteByte(',')
		}
		k, _ := json.Marshal(e.K)
		b.Write(k)
		b.WriteByte(':')
		v, err := marshal(e.V)
		if err != nil {
			return nil, err
		}
		b.Write(v)
	}
	b.WriteByte('}')
	return b.Bytes(), nil
}

func (o obj) get(k string) any {
	for _, e := range o {
		if e.K == k {
			return e.V
		}
	}
	return nil
}

func (o obj) set(k string, v any) obj {
	for i, e := range o {
		if e.K == k {
			o[i].V = v
			return o
		}
	}
	return append(o, kv{k, v})
}

func marshal(v any) ([]byte, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return bytes.TrimRight(b.Bytes(), "\n"), nil
}

func pretty(v any) ([]byte, error) {
	raw, err := marshal(v)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	if err := json.Indent(&b, raw, "", "  "); err != nil {
		return nil, err
	}
	b.WriteByte('\n')
	return b.Bytes(), nil
}

// decodeOrdered parses a JSON object keeping key order (nested objects too).
func decodeOrdered(raw []byte) (any, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	v, err := decodeValue(dec)
	if err != nil {
		return nil, err
	}
	if _, err := dec.Token(); err != io.EOF {
		return nil, errors.New("trailing data")
	}
	return v, nil
}

func decodeValue(dec *json.Decoder) (any, error) {
	t, err := dec.Token()
	if err != nil {
		return nil, err
	}
	switch d := t.(type) {
	case json.Delim:
		switch d {
		case '{':
			o := obj{}
			for dec.More() {
				kt, err := dec.Token()
				if err != nil {
					return nil, err
				}
				v, err := decodeValue(dec)
				if err != nil {
					return nil, err
				}
				o = append(o, kv{kt.(string), v})
			}
			_, err := dec.Token()
			return o, err
		case '[':
			a := []any{}
			for dec.More() {
				v, err := decodeValue(dec)
				if err != nil {
					return nil, err
				}
				a = append(a, v)
			}
			_, err := dec.Token()
			return a, err
		}
	}
	return t, nil
}

func sha256Hex(b []byte) string { h := sha256.Sum256(b); return hex.EncodeToString(h[:]) }

func seeded(label string) []byte {
	h := sha256.Sum256([]byte("common-relay/test-vector/" + label))
	return h[:]
}

/* ───────── vectors.json: secret hashing, stream frames, trust matrix ───────── */

func coreVectors() ([]byte, error) {
	hashCases := []kv{
		{"access password (Relay-Access)", "common-relay-v2-vector-secret"},
		{"device bearer token", strings.Repeat("0123456789abcdef", 4)},
		{"invitation secret", "public-test-invitation"},
		{"utf-8 input", "设备-ünïcode"},
		{"empty string", ""},
	}
	hashes := []any{}
	for _, c := range hashCases {
		in := c.V.(string)
		got := core.HashSecret(in)
		if got != v2client.HashSecret(in) {
			return nil, errors.New("server and Go SDK HashSecret disagree")
		}
		hashes = append(hashes, obj{{"use", c.K}, {"input", in}, {"sha256", got}})
	}
	streamID, payload := "0123456789abcdef", "ZIP_STREAM_CHUNK_DATA"
	frame := append([]byte(streamID), payload...)
	levels := []core.TrustLevel{core.TrustStrictE2E, core.TrustClientEncrypted, core.TrustBridgeAllowed}
	matrix := []any{}
	for _, space := range levels {
		for _, plugin := range levels {
			matrix = append(matrix, obj{{"space", string(space)}, {"plugin", string(plugin)}, {"allowed", space.Allows(plugin)}})
		}
	}
	return pretty(obj{
		{"version", 2},
		{"note", generatedNote},
		{"hash_secret", hashes},
		{"binary_stream_frame", obj{{"stream_id", streamID}, {"payload_utf8", payload}, {"frame_hex", hex.EncodeToString(frame)}}},
		{"trust_matrix", matrix},
	})
}

/* ───────── sealed-vectors.json: crs1 bridge payloads ───────── */

const (
	crs1Magic  = "CRS1"
	crs1Chunk  = 64 << 10
	crs1Header = 4 + 32 + box.AnonymousOverhead + 16
)

// sealDeterministic is v2client.SealStream with every random input derived
// from label, so the output is reproducible.
func sealDeterministic(label string, recipient *[32]byte, plain []byte) ([]byte, error) {
	var key [32]byte
	copy(key[:], seeded("crs1/content-key/"+label))
	sealedKey, err := box.SealAnonymous(nil, key[:], recipient, bytes.NewReader(seeded("crs1/ephemeral/"+label)))
	if err != nil {
		return nil, err
	}
	var prefix [16]byte
	copy(prefix[:], seeded("crs1/prefix/"+label))
	out := append([]byte(crs1Magic), sealedKey...)
	out = append(out, prefix[:]...)
	for ctr := uint64(0); ; ctr++ {
		n := min(crs1Chunk, len(plain))
		chunk := plain[:n]
		plain = plain[n:]
		c := ctr
		if len(plain) == 0 {
			c |= 1 << 63
		}
		var nonce [24]byte
		copy(nonce[:16], prefix[:])
		binary.BigEndian.PutUint64(nonce[16:], c)
		ct := secretbox.Seal(nil, chunk, &nonce, &key)
		out = binary.BigEndian.AppendUint32(out, uint32(len(ct)))
		out = append(out, ct...)
		if len(plain) == 0 {
			return out, nil
		}
	}
}

func patternBytes(n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = byte(i*7 + 3)
	}
	return b
}

func sealedVectors() ([]byte, error) {
	var priv, otherPriv [32]byte
	for i := range priv {
		priv[i], otherPriv[i] = 0x42, 0x24
	}
	pub, err := curve25519.X25519(priv[:], curve25519.Basepoint)
	if err != nil {
		return nil, err
	}
	otherPub, _ := curve25519.X25519(otherPriv[:], curve25519.Basepoint)
	var recipient [32]byte
	copy(recipient[:], pub)
	cases := []struct {
		name  string
		plain []byte
		small bool
	}{
		{"hello", []byte("hello sealed crs1"), true},
		{"empty", []byte{}, true},
		{"two_frames", patternBytes(crs1Chunk + 7), false},
	}
	valid := []any{}
	sealed := map[string][]byte{}
	for _, c := range cases {
		s, err := sealDeterministic(c.name, &recipient, c.plain)
		if err != nil {
			return nil, err
		}
		got, err := v2client.OpenSealed(s, &recipient, &priv)
		if err != nil || !bytes.Equal(got, c.plain) {
			return nil, fmt.Errorf("Go SDK cannot open %s: %v", c.name, err)
		}
		sealed[c.name] = s
		e := obj{{"name", c.name}}
		if c.small {
			e = append(e, kv{"plaintext_hex", hex.EncodeToString(c.plain)})
		} else {
			e = append(e, kv{"plaintext_pattern", "byte[i] = (i*7 + 3) mod 256"})
		}
		e = append(e, kv{"plaintext_length", len(c.plain)}, kv{"plaintext_sha256", sha256Hex(c.plain)}, kv{"sealed_b64", base64.StdEncoding.EncodeToString(s)})
		valid = append(valid, e)
	}
	hello := sealed["hello"]
	firstFrame := crs1Header + 4 + crs1Chunk + secretbox.Overhead
	invalid := []obj{
		{{"name", "truncated_last_byte"}, {"base", "hello"}, {"op", "truncate"}, {"length", len(hello) - 1}},
		{{"name", "header_only"}, {"base", "hello"}, {"op", "truncate"}, {"length", crs1Header}},
		{{"name", "dropped_final_frame"}, {"base", "two_frames"}, {"op", "truncate"}, {"length", firstFrame}},
		{{"name", "trailing_byte"}, {"base", "hello"}, {"op", "append"}, {"hex", "00"}},
		{{"name", "flipped_magic"}, {"base", "hello"}, {"op", "flip"}, {"offset", 0}},
		{{"name", "flipped_sealed_key"}, {"base", "hello"}, {"op", "flip"}, {"offset", 10}},
		{{"name", "flipped_prefix"}, {"base", "hello"}, {"op", "flip"}, {"offset", 90}},
		{{"name", "flipped_frame_length"}, {"base", "hello"}, {"op", "flip"}, {"offset", crs1Header + 3}},
		{{"name", "flipped_ciphertext"}, {"base", "hello"}, {"op", "flip"}, {"offset", len(hello) - 1}},
	}
	invalidOut := []any{}
	for _, m := range invalid {
		b, err := mutate(sealed[m.get("base").(string)], m)
		if err != nil {
			return nil, err
		}
		if _, err := v2client.OpenSealed(b, &recipient, &priv); err == nil {
			return nil, fmt.Errorf("invalid case %s opens", m.get("name"))
		}
		invalidOut = append(invalidOut, m)
	}
	var other, otherSecret [32]byte
	copy(other[:], otherPub)
	copy(otherSecret[:], otherPriv[:])
	if _, err := v2client.OpenSealed(hello, &other, &otherSecret); err == nil {
		return nil, errors.New("hello opens with the wrong key")
	}
	return pretty(obj{
		{"version", 1},
		{"note", generatedNote},
		{"format", "\"CRS1\" | box.SealAnonymous(content_key) (80) | nonce_prefix (16) | frames: u32be len | secretbox(chunk <= 65536, prefix || u64be counter, final frame sets bit 63)"},
		{"content_type", v2client.SealedContentType},
		{"recipient_public", hex.EncodeToString(pub)},
		{"recipient_private", hex.EncodeToString(priv[:])},
		{"wrong_public", hex.EncodeToString(otherPub)},
		{"wrong_private", hex.EncodeToString(otherPriv[:])},
		{"valid", valid},
		{"invalid_note", "apply op to the named valid case: truncate to length bytes, append hex bytes, or flip (xor 0x01) the byte at offset; opening must fail. hello must also fail with the wrong_* key pair."},
		{"invalid", invalidOut},
	})
}

func mutate(base []byte, m obj) ([]byte, error) {
	b := append([]byte(nil), base...)
	switch m.get("op") {
	case "truncate":
		return b[:m.get("length").(int)], nil
	case "append":
		x, err := hex.DecodeString(m.get("hex").(string))
		return append(b, x...), err
	case "flip":
		b[m.get("offset").(int)] ^= 1
		return b, nil
	}
	return nil, errors.New("unknown op")
}

/* ───────── group-vectors.json ───────── */

const groupSigningDomain = "common-relay/group-signing/v1\x00"

// signingKey derives the Ed25519 key of a test device whose X25519 secret is 32×b.
func signingKey(b byte) ed25519.PrivateKey {
	h := sha256.New()
	h.Write([]byte(groupSigningDomain))
	h.Write(bytes.Repeat([]byte{b}, 32))
	return ed25519.NewKeyFromSeed(h.Sum(nil))
}

var (
	macKey      = signingKey(0x01)
	phoneKey    = signingKey(0x02)
	delegateKey = signingKey(0x71)
)

func pubHex(k ed25519.PrivateKey) string { return hex.EncodeToString(k.Public().(ed25519.PublicKey)) }

func sign(raw []byte, k ed25519.PrivateKey, signer string) obj {
	return obj{{"payload", base64.StdEncoding.EncodeToString(raw)}, {"signature", hex.EncodeToString(ed25519.Sign(k, raw))}, {"signer", signer}}
}

func entryPayload(e any) ([]byte, error) {
	o, ok := e.(obj)
	if !ok {
		return nil, errors.New("entry is not an object")
	}
	p, _ := o.get("payload").(string)
	return base64.StdEncoding.Strict().DecodeString(p)
}

func verifyEntry(e any, key string) bool {
	raw, err := entryPayload(e)
	o, _ := e.(obj)
	sig, se := hex.DecodeString(fmt.Sprint(o.get("signature")))
	pk, pe := hex.DecodeString(key)
	return err == nil && se == nil && pe == nil && len(pk) == 32 && len(sig) == 64 && ed25519.Verify(pk, raw, sig)
}

// lookup resolves a dotted path ("auto_admission.grant") in the ordered document.
func lookup(doc obj, path string) any {
	var cur any = doc
	for _, p := range strings.Split(path, ".") {
		o, ok := cur.(obj)
		if !ok {
			return nil
		}
		cur = o.get(p)
	}
	return cur
}

func groupVectors(raw []byte) ([]byte, error) {
	v, err := decodeOrdered(raw)
	if err != nil {
		return nil, err
	}
	doc := v.(obj)
	if pubHex(macKey) != fmt.Sprint(lookup(doc, "manager.signing_key")) || pubHex(phoneKey) != fmt.Sprint(lookup(doc, "new_member.signing_key")) {
		return nil, errors.New("base fixture keys do not match the fixed seeds")
	}
	config := lookup(doc, "config").(obj)
	config = config.set("url", "wss://relay.example.com/v2/ws")
	doc = doc.set("note", "Public test identities only; never deploy. Base fixtures are frozen signed entries; config, strict_payload and entry_hashes are maintained by `go run ./scripts/protocol-vectors`.")
	doc = doc.set("config", config)

	strict, err := strictPayload(doc)
	if err != nil {
		return nil, err
	}
	doc = doc.set("strict_payload", strict)

	grantRaw, err := entryPayload(lookup(doc, "auto_admission.grant"))
	if err != nil {
		return nil, err
	}
	var grant struct {
		DelegateKey string `json:"delegate_key"`
	}
	if json.Unmarshal(grantRaw, &grant) != nil || grant.DelegateKey != pubHex(delegateKey) {
		return nil, errors.New("grant delegate key does not match the fixed seed")
	}
	mac, phone := pubHex(macKey), pubHex(phoneKey)
	hashes := []any{}
	for _, c := range []struct {
		path, key string
		valid     bool
	}{
		{"initial", mac, true},
		{"initial", phone, false},
		{"request", phone, true},
		{"approved", mac, true},
		{"removed", mac, true},
		{"self_service", mac, true},
		{"left", phone, true},
		{"disbanded", mac, true},
		{"renamed", phone, true},
		{"renamed", mac, false},
		{"auto_admission.grant", mac, true},
		{"auto_admission.approved", grant.DelegateKey, true},
		{"auto_admission.approved", mac, false},
	} {
		e := lookup(doc, c.path)
		payload, err := entryPayload(e)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", c.path, err)
		}
		if verifyEntry(e, c.key) != c.valid {
			return nil, fmt.Errorf("%s: signature validity under %s is not %v", c.path, c.key[:8], c.valid)
		}
		hashes = append(hashes, obj{{"entry", c.path}, {"payload_sha256", sha256Hex(payload)}, {"verify_key", c.key}, {"signature_valid", c.valid}})
	}
	// Chain links: every advance's "previous" is the SHA-256 of its base payload.
	for _, link := range [][2]string{{"initial", "approved"}, {"approved", "removed"}, {"approved", "left"}, {"approved", "disbanded"}, {"approved", "renamed"}, {"initial", "auto_admission.approved"}} {
		base, _ := entryPayload(lookup(doc, link[0]))
		next, _ := entryPayload(lookup(doc, link[1]))
		var st struct {
			Previous string `json:"previous"`
		}
		if json.Unmarshal(next, &st) != nil || st.Previous != sha256Hex(base) {
			return nil, fmt.Errorf("%s.previous is not sha256(%s)", link[1], link[0])
		}
	}
	doc = doc.set("entry_hashes", obj{
		{"note", "payload_sha256 = lowercase hex SHA-256 of the base64-decoded payload bytes (the next state's \"previous\"). signature_valid = Ed25519 verify(verify_key, payload bytes, signature)."},
		{"cases", hashes},
		{"links", []any{
			obj{{"base", "initial"}, {"next", "approved"}},
			obj{{"base", "approved"}, {"next", "removed"}},
			obj{{"base", "approved"}, {"next", "left"}},
			obj{{"base", "approved"}, {"next", "disbanded"}},
			obj{{"base", "approved"}, {"next", "renamed"}},
			obj{{"base", "initial"}, {"next", "auto_admission.approved"}},
		}},
	})
	return pretty(doc)
}

// strictPayload derives the strict_payload section: entries signed correctly by
// a member allowed to make the change but encoded ambiguously.
func strictPayload(doc obj) (obj, error) {
	renamedRaw, err := entryPayload(lookup(doc, "renamed"))
	if err != nil {
		return nil, err
	}
	renamed := string(renamedRaw)
	const member = `"name":"我的手机"`
	const phone = `"device":"phone",` + member
	if strings.Count(renamed, phone) != 1 || strings.Count(renamed, `"manager":false`) != 1 {
		return nil, errors.New("unexpected renamed fixture")
	}
	var bad error
	rename := func(old, new string) obj {
		if strings.Count(renamed, old) != 1 {
			bad = fmt.Errorf("renamed fixture lacks %q", old)
		}
		return sign([]byte(strings.Replace(renamed, old, new, 1)), phoneKey, "phone")
	}
	c := func(name string, e obj) obj { return obj{{"case", name}, {"entry", e}} }

	renamedEntry := lookup(doc, "renamed").(obj)
	newline := append(obj(nil), renamedEntry...)
	p := renamedEntry.get("payload").(string)
	newline = newline.set("payload", p[:40]+"\n"+p[40:])

	grantRaw, err := entryPayload(lookup(doc, "auto_admission.grant"))
	if err != nil {
		return nil, err
	}
	auto := append(obj(nil), lookup(doc, "auto_admission.approved").(obj)...)
	auto = auto.set("authorization", sign(bytes.Replace(grantRaw, []byte(`"anchor_hash"`), []byte(`"extra":1,"anchor_hash"`), 1), macKey, "mac"))

	valid := c("whitespace_and_escapes", rename(member, ` "name" : "\u6211\u7684\/\u624b\u673a" `))
	invalid := []any{
		c("unknown_member_field", rename(phone, phone+`,"evil":1`)),
		c("case_variant_key", rename(phone, phone+`,"Manager":true`)),
		c("duplicate_key", rename(`"manager":false`, `"manager":true,"manager":false`)),
		c("escaped_key", rename(`"manager":false`, `"m\u0061nager":false`)),
		c("unknown_state_field", rename(`"version":1,`, `"version":1,"extra":"x",`)),
		c("null_value", rename(`"invitation":""`, `"invitation":null`)),
		c("fraction_number", rename(`"revision":3`, `"revision":3.0`)),
		c("exponent_number", rename(`"revision":3`, `"revision":3e0`)),
		c("leading_zero_number", rename(`"version":1`, `"version":01`)),
		c("bool_as_number", rename(`"manager":false`, `"manager":0`)),
		c("number_as_string", rename(`"revision":3`, `"revision":"3"`)),
		c("missing_field", rename(`,"request_hash":""`, ``)),
		c("lone_surrogate", rename(member, `"name":"\ud800"`)),
		c("trailing_data", sign([]byte(renamed+"{}"), phoneKey, "phone")),
		c("base64_newline", newline),
	}
	if bad != nil {
		return nil, bad
	}
	canonical := valid.get("entry").(obj)
	text := canonical.get("payload").(string)
	const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
	idx := len(strings.TrimRight(text, "=")) - 1
	noncanonical := text[:idx] + string(alphabet[strings.IndexByte(alphabet, text[idx])|1]) + text[idx+1:]
	for _, alt := range []struct{ name, payload string }{
		{"base64_missing_padding", strings.TrimRight(text, "=")},
		{"base64_nonzero_pad_bits", noncanonical},
		{"base64_wrapped_valid_payload", text[:20] + "\n" + text[20:]},
	} {
		e := append(obj(nil), canonical...)
		invalid = append(invalid, c(alt.name, e.set("payload", alt.payload)))
	}
	return obj{
		{"note", "invalid entries are signed correctly but encoded ambiguously and must be rejected; valid must be accepted. Base is approved; invalid_auto base is initial."},
		{"valid", []any{valid}},
		{"invalid", invalid},
		{"invalid_auto", []any{c("grant_unknown_field", auto)}},
	}, nil
}

