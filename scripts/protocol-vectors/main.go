// invitationVectors keeps the frozen access_password / invalid_link_suffixes
// inputs of the existing file and derives everything else.
func invitationVectors(groupRaw, linkRaw []byte) ([]byte, error) {
	lv, err := decodeOrdered(linkRaw)
	if err != nil {
		return nil, err
	}
	frozen := lv.(obj)
	password, _ := frozen.get("access_password").(string)
	suffixes, _ := frozen.get("invalid_link_suffixes").([]any)
	if password == "" || len(suffixes) == 0 {
		return nil, errors.New("access_password / invalid_link_suffixes inputs missing")
	}
	v, err := decodeOrdered(groupRaw)
	if err != nil {
		return nil, err
	}
	doc := v.(obj)
	manager := lookup(doc, "manager")
	grant := lookup(doc, "auto_admission.grant")
	const host = "relay.example.com"
	inv := obj{
		{"version", 1},
		{"mode", "auto"},
		{"url", "wss://" + host + "/v2/ws"},
		{"app", "example"},
		{"group", "vectors"},
		{"id", "abababababababababababababababab"},
		{"expires", 2000000000},
		{"secret", "public-test-invitation"},
		{"manager", manager},
		{"grant", grant},
		{"delegate_secret", strings.Repeat("71", 32)},
	}
	var key [32]byte
	var nonce [24]byte
	for i := range key {
		key[i] = byte(i)
	}
	for i := range nonce {
		nonce[i] = byte(i)
	}
	plain, err := marshal(obj{{"version", 1}, {"purpose", "common-relay/invitation-link/v1"}, {"invitation", inv}})
	if err != nil {
		return nil, err
	}
	packet := base64.StdEncoding.EncodeToString(secretbox.Seal(nonce[:], plain, &nonce, &key))
	rt := sha256.New()
	rt.Write([]byte("common-relay/invitation-link/read/v1\x00"))
	rt.Write(key[:])
	readToken := hex.EncodeToString(rt.Sum(nil))
	id, _ := hex.DecodeString("abababababababababababababababab")
	b64 := base64.RawURLEncoding.EncodeToString
	link := "common-relay://" + host + "/v2/i/" + b64(id) + "#" + b64(key[:])
	idPart := b64(id)
	return pretty(obj{
		{"note", generatedNote},
		{"invitation", inv},
		{"key", hex.EncodeToString(key[:])},
		{"nonce", hex.EncodeToString(nonce[:])},
		{"packet_plaintext", string(plain)},
		{"packet", packet},
		{"read_token", readToken},
		{"read_hash", core.HashSecret(readToken)},
		{"link", link},
		{"link_length", len(link)},
		{"access_password", password},
		{"link_with_password", link + "." + b64([]byte(password))},
		{"invalid_link_suffixes", suffixes},
		{"invalid_links", []any{
			"common-relay://" + host + "/i/" + idPart + "#" + b64(key[:]),
			"common-relay://" + host + "/v2/j/" + idPart + "#" + b64(key[:]),
			"common-relay://" + host + "/v2/i/" + idPart + "=#" + b64(key[:]),
			"common-relay://" + host + "/v2/i/" + idPart + "#" + b64(key[:]) + "=",
			"common-relay://" + host + "/v2/i/" + idPart + "#" + b64(key[:31]),
			"common-relay://user@" + host + "/v2/i/" + idPart + "#" + b64(key[:]),
			"common-relay://" + host + "/v2/i/" + idPart + "?x=1#" + b64(key[:]),
			"https://" + host + "/v2/i/" + idPart + "#" + b64(key[:]),
		}},
	})
}
